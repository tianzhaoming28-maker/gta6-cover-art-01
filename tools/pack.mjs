// Packs the entry's binary payloads into TypeScript data files at the repo
// root. Real binaries live only in screenshots-src/ and assets-src/ (both
// gitignored); the committed repo carries them as base64, ONE SINGLE LINE
// per payload, and main.ts materialises them again into /output.
//   node tools/pack.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

/** Reads a directory's image files into { name, base64 } rows, name order. */
function packDir(dir) {
  return readdirSync(join(root, dir))
    .filter((name) => /\.(png|jpe?g)$/i.test(name))
    .sort()
    .map((name) => ({ name, base64: readFileSync(join(root, dir, name)).toString('base64') }));
}

/** Writes one payload module: a header plus one single-line entry per file. */
function writePayload(file, exportName, rows, sourceDir) {
  const lines = [
    `// Packed binary payloads from ${sourceDir}/ — generated by tools/pack.mjs.`,
    '// Each payload is one single line of base64; main.ts decodes them into /output.',
    `export const ${exportName} = [`,
    ...rows.map((row) => `  { name: ${JSON.stringify(row.name)}, base64: '${row.base64}' },`),
    '];',
    '',
  ];
  writeFileSync(join(root, file), lines.join('\n'));
  const total = rows.reduce((sum, row) => sum + row.base64.length, 0);
  console.log(`${file}: ${rows.length} payloads, ${total} base64 chars`);
}

writePayload('screenshots-data.ts', 'SCREENSHOT_FILES', packDir('screenshots-src'), 'screenshots-src');
writePayload('samples-data.ts', 'SAMPLE_FILES', packDir('assets-src'), 'assets-src');
